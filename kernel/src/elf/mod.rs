pub fn run_negative_tests() -> bool {
    // Test 1: File too short
    let short_data = &[0x7F, b'E', b'L', b'F'];
    if validate_elf_headers(short_data).is_ok() {
        return false;
    }

    // Test 2: Invalid magic
    let mut bad_magic = [0u8; 188];
    bad_magic.copy_from_slice(ELF_HELLO_BIN);
    bad_magic[0..4].copy_from_slice(b"NOVA");
    if validate_elf_headers(&bad_magic).is_ok() {
        return false;
    }

    // Test 3: 32-bit ELF class (ELFCLASS32 = 1)
    let mut bad_class = [0u8; 188];
    bad_class.copy_from_slice(ELF_HELLO_BIN);
    bad_class[4] = 1;
    if validate_elf_headers(&bad_class).is_ok() {
        return false;
    }

    // Test 4: Big-endian encoding (ELFDATA2MSB = 2)
    let mut bad_endian = [0u8; 188];
    bad_endian.copy_from_slice(ELF_HELLO_BIN);
    bad_endian[5] = 2;
    if validate_elf_headers(&bad_endian).is_ok() {
        return false;
    }

    // Test 5: Unsupported architecture (e.g. ARM64 = 183)
    let mut bad_arch = [0u8; 188];
    bad_arch.copy_from_slice(ELF_HELLO_BIN);
    bad_arch[18] = 0xB7; // 183
    bad_arch[19] = 0x00;
    if validate_elf_headers(&bad_arch).is_ok() {
        return false;
    }

    // Test 6: p_memsz < p_filesz
    let mut bad_sizes = [0u8; 188];
    bad_sizes.copy_from_slice(ELF_HELLO_BIN);
    // Program header p_memsz is at offset 64 + 40 = 104
    bad_sizes[104] = 10; // p_memsz = 10 < p_filesz
    if validate_elf_headers(&bad_sizes).is_ok() {
        return false;
    }

    // Test 7: Kernel space conflict
    let mut kernel_conflict = [0u8; 188];
    kernel_conflict.copy_from_slice(ELF_HELLO_BIN);
    // Program header p_vaddr is at offset 64 + 16 = 80
    kernel_conflict[80..88].copy_from_slice(&0xFFFF_8000_0000_0000u64.to_le_bytes());
    if validate_elf_headers(&kernel_conflict).is_ok() {
        return false;
    }

    // Test 8: Invalid entry point outside executable segment
    let mut bad_entry = [0u8; 188];
    bad_entry.copy_from_slice(ELF_HELLO_BIN);
    // e_entry is at offset 24
    bad_entry[24..32].copy_from_slice(&0x0000_0000_0010_0000u64.to_le_bytes());
    if validate_elf_headers(&bad_entry).is_ok() {
        return false;
    }

    // Test 9: Pointer validation security tests
    if !crate::userspace::test_invalid_user_pointer() {
        return false;
    }

    true
}
